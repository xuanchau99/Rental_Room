-- Monetary values use decimal; meter readings use kWh and m3.

CREATE TABLE properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    property_id BIGINT NOT NULL REFERENCES properties(id),
    code VARCHAR(30) NOT NULL,
    area_m2 NUMERIC(8, 2) NOT NULL CHECK (area_m2 > 0),
    has_mezzanine BOOLEAN NOT NULL,
    has_air_conditioner BOOLEAN NOT NULL,
    monthly_rent NUMERIC(14, 2) CHECK (monthly_rent >= 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('VACANT', 'OCCUPIED', 'MAINTENANCE')),
    UNIQUE (property_id, code)
);
CREATE INDEX idx_rooms_property_id ON rooms (property_id);

CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    identity_number VARCHAR(50),
    date_of_birth DATE
);

CREATE TABLE contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    start_date DATE NOT NULL,
    end_date DATE,
    monthly_rent NUMERIC(14, 2) NOT NULL CHECK (monthly_rent >= 0),
    deposit_amount NUMERIC(14, 2) NOT NULL CHECK (deposit_amount >= 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ENDED', 'CANCELLED')),
    CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX idx_contracts_room_id ON contracts (room_id);
CREATE INDEX idx_contracts_tenant_id ON contracts (tenant_id);

CREATE TABLE electricity_meters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    reading_date DATE NOT NULL,
    reading NUMERIC(14, 3) NOT NULL CHECK (reading >= 0),
    UNIQUE (room_id, reading_date)
);
CREATE INDEX idx_electricity_meters_room_id ON electricity_meters (room_id);

CREATE TABLE water_meters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    reading_date DATE NOT NULL,
    reading NUMERIC(14, 3) NOT NULL CHECK (reading >= 0),
    UNIQUE (room_id, reading_date)
);
CREATE INDEX idx_water_meters_room_id ON water_meters (room_id);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    contract_id BIGINT NOT NULL REFERENCES contracts(id),
    number VARCHAR(50) NOT NULL UNIQUE,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    due_date DATE NOT NULL,
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'CANCELLED')),
    CHECK (period_end >= period_start)
);
CREATE INDEX idx_invoices_contract_id ON invoices (contract_id);

CREATE TABLE invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    type VARCHAR(30) NOT NULL CHECK (type IN ('RENT', 'ELECTRICITY', 'WATER', 'SERVICE', 'OTHER')),
    description VARCHAR(255) NOT NULL,
    quantity NUMERIC(14, 3) NOT NULL CHECK (quantity >= 0),
    unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0)
);
CREATE INDEX idx_invoice_items_invoice_id ON invoice_items (invoice_id);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0),
    paid_at TIMESTAMPTZ NOT NULL,
    method VARCHAR(30) NOT NULL CHECK (method IN ('CASH', 'BANK_TRANSFER', 'OTHER')),
    reference VARCHAR(100)
);
CREATE INDEX idx_payments_invoice_id ON payments (invoice_id);
