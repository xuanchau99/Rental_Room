CREATE TABLE service_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    contract_id BIGINT NOT NULL REFERENCES contracts(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    billing_month INTEGER NOT NULL CHECK (billing_month BETWEEN 1 AND 12),
    billing_year INTEGER NOT NULL CHECK (billing_year BETWEEN 2000 AND 9999),
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity>=0),
    UNIQUE(contract_id,service_id,billing_year,billing_month)
);
CREATE INDEX idx_service_usages_contract_id ON service_usages(contract_id);
CREATE INDEX idx_service_usages_service_id ON service_usages(service_id);
