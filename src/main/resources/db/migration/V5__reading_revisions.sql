CREATE TABLE electricity_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reading_id BIGINT NOT NULL REFERENCES electricity_meters(id),
    old_reading NUMERIC(14,3) NOT NULL CHECK (old_reading >= 0),
    new_reading NUMERIC(14,3) NOT NULL CHECK (new_reading >= 0),
    changed_by VARCHAR(100) NOT NULL,
    reason VARCHAR(1000) NOT NULL
);
CREATE INDEX idx_electricity_revisions_reading_id ON electricity_revisions(reading_id);
